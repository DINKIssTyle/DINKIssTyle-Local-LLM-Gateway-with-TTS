#!/usr/bin/env python3
"""Offline skill-routing experiment; never runs a skill or modifies app state.

Run with the app's pinned MediaPipe 1.1.0 environment and local 440M model.
Expected labels are authored fixtures, not answers generated by another LLM.
"""
import argparse
import hashlib
import importlib.metadata
import json
import platform
import random
import re
import statistics
import time
from pathlib import Path


SKILL_NAMES = ("msn-weather-current", "python-calculator")
LABELS = {"none": [], "weather": [SKILL_NAMES[0]], "calculator": [SKILL_NAMES[1]], "both": list(SKILL_NAMES)}


def percentile(values, fraction):
    ordered = sorted(values)
    if not ordered:
        return None
    position = (len(ordered) - 1) * fraction
    lo, hi = int(position), min(int(position) + 1, len(ordered) - 1)
    return round(ordered[lo] + (ordered[hi] - ordered[lo]) * (position - lo), 3)


def metrics(rows):
    required = missing = extra = exact = errors = none_count = false_activations = 0
    for row in rows:
        wanted, got = set(row["expected"]), set(row["predicted"])
        required += len(wanted)
        missing += len(wanted - got)
        extra += len(got - wanted)
        exact += wanted == got and not row.get("error")
        errors += bool(row.get("error"))
        if not wanted:
            none_count += 1
            false_activations += bool(got)
    elapsed = [row["elapsed_ms"] for row in rows]
    return {
        "requests": len(rows), "exact_matches": exact,
        "exact_accuracy": round(exact / len(rows), 4) if rows else None,
        "required_skill_recall": round((required - missing) / required, 4) if required else None,
        "missing_required_skills": missing, "extra_skills": extra, "errors": errors,
        "no_skill_requests": none_count, "false_activations_on_no_skill": false_activations,
        "latency_ms": {"p50": percentile(elapsed, .5), "p95": percentile(elapsed, .95), "max": round(max(elapsed), 3) if elapsed else None},
        "over_2_seconds": sum(value > 2000 for value in elapsed),
    }


def summarize(report):
    """Compute metrics without additional inference or threshold fitting."""
    for strategy in ["english_choice", "korean_choice", "per_skill_boolean"]:
        rows = [row for row in report["results"] if row["strategy"] == strategy]
        summary = {"all": metrics(rows)}
        for split in ["development", "heldout"]:
            subset = [row for row in rows if row["split"] == split]
            summary[split] = metrics(subset)
            summary[split + "_explicit_guard"] = metrics([{**row, "predicted": row["guarded_predicted"]} for row in subset])
        summary["heldout_by_group"] = {}
        summary["heldout_guarded_by_group"] = {}
        for label, expected in LABELS.items():
            subset = [row for row in rows if row["split"] == "heldout" and set(row["expected"]) == set(expected)]
            summary["heldout_by_group"][label] = metrics(subset)
            summary["heldout_guarded_by_group"][label] = metrics([{**row, "predicted": row["guarded_predicted"]} for row in subset])
        summary["heldout_by_language"] = {}
        for language, korean in [("Korean", True), ("English", False)]:
            subset = [row for row in rows if row["split"] == "heldout" and bool(re.search("[가-힣]", row["text"])) == korean]
            summary["heldout_by_language"][language] = metrics(subset)
        ids = sorted({row["id"] for row in rows})
        summary["inconsistent_cases"] = [case_id for case_id in ids if len({
            tuple(row["predicted"]) for row in rows if row["id"] == case_id}) > 1]
        if strategy.endswith("choice"):
            # Post-hoc diagnostic, not a separately validated deployment gate:
            # retain all skills whenever the largest category mass is < .90.
            # This is category probability, NOT SDK `confidence` or measured
            # correctness probability for a skill-routing task.
            subset = [row for row in rows if row["split"] == "heldout"]
            candidate_rows = [{**row, "predicted": row["guarded_predicted"] if max(row["probabilities"].values(), default=0) >= .90 else list(SKILL_NAMES)} for row in subset]
            summary["posthoc_candidates_0_90"] = {
                "scope": "Exploratory only; evaluated after inspecting test errors. Must validate on new cases before production use.",
                "metrics": metrics(candidate_rows),
                "requests_with_fewer_than_two_candidates": sum(len(row["predicted"]) < 2 for row in candidate_rows),
                "mean_candidates": round(statistics.mean(len(row["predicted"]) for row in candidate_rows), 4),
            }
        report["summary"][strategy] = summary


def main():
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model", type=Path, required=True)
    parser.add_argument("--cases", type=Path, default=root / "evals/jev-skills/cases.json")
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--rounds", type=int, default=3)
    args = parser.parse_args()
    if args.rounds < 1:
        parser.error("--rounds must be positive")
    cases = json.loads(args.cases.read_text())
    descriptions, hashes = {}, {}
    for name in SKILL_NAMES:
        path = root / "bundle/skills/builtin" / name / "SKILL.md"
        content = path.read_text()
        descriptions[name] = re.search(r"^description: (.+)$", content, re.M).group(1)
        hashes[name] = hashlib.sha256(path.read_bytes()).hexdigest()
    assert len({case["id"] for case in cases}) == len(cases)
    assert all(set(case["expected"]) <= set(SKILL_NAMES) for case in cases)

    from mediapipe.tasks.python import BaseOptions, decision
    load_started = time.perf_counter()
    engine = decision.DecisionMaker.create_from_options(decision.DecisionMakerOptions(
        base_options=BaseOptions(model_asset_path=str(args.model)), max_num_tokens=2048))
    load_ms = (time.perf_counter() - load_started) * 1000
    english = decision.ChoiceQuestion(criteria={
        "none": "The user needs neither a current-weather lookup nor a precise mathematical or date calculation. Explain concepts, translate, write, code, or answer normally.",
        "weather": "The user needs only this procedure: " + descriptions[SKILL_NAMES[0]],
        "calculator": "The user needs only this procedure: " + descriptions[SKILL_NAMES[1]],
        "both": "The user needs BOTH a current-weather lookup AND a precise numerical or calendar calculation in the same request.",
    }, instructions="Choose the procedures required by the user's actual intent. Merely mentioning weather, dates or Python does not require a procedure. A request may require both procedures or none. An explicit $skill request takes priority.")
    korean = decision.ChoiceQuestion(criteria={
        "none": "현재 날씨 조회와 정확한 수치·날짜 계산이 모두 필요 없다. 개념 설명, 번역, 글쓰기, 코드 작성, 개인 기억 질문은 여기에 해당한다.",
        "weather": "현재 날씨, 기온, 체감온도, 습도, 강수, 바람을 실제로 조회해야 한다. 정확한 수치·날짜 계산은 필요 없다.",
        "calculator": "정확한 날짜 차이, 요일, 만 나이, 복잡한 수학, 이자, 통계 또는 수치 계산이 필요하다. 현재 날씨 조회는 필요 없다.",
        "both": "동일한 요청에 현재 날씨를 실제로 조회하는 작업과 정확한 수치·날짜 계산이 모두 필요하다.",
    }, instructions="사용자의 실제 의도에 필요한 스킬을 선택한다. 날씨·날짜·Python 단어만 등장하는 것으로 스킬을 적용하지 않는다. 스킬 없음과 두 스킬 모두를 허용한다. $스킬명으로 명시된 요청은 우선한다.")
    booleans = {
        name: decision.BooleanQuestion(condition="The user's intent requires the following procedure, rather than merely discussing its topic. An explicit $" + name + " request also requires it. Procedure: " + descriptions[name], threshold=.5)
        for name in SKILL_NAMES
    }
    questions = {"english_choice": english, "korean_choice": korean}
    prewarm = {}
    for name, question in questions.items():
        started = time.perf_counter()
        engine.prewarm_choice(question)
        prewarm[name] = round((time.perf_counter() - started) * 1000, 3)
    for name, question in booleans.items():
        started = time.perf_counter()
        # This SDK only exposes explicit prewarming for Choice questions.
        # Warm each Boolean with a separate non-evaluation input.
        engine.evaluate_boolean("Warmup request: hello.", question)
        prewarm[name] = round((time.perf_counter() - started) * 1000, 3)

    report = {
        "metadata": {
            "model": args.model.name, "mediapipe": importlib.metadata.version("mediapipe"),
            "python": platform.python_version(), "platform": platform.platform(),
            "max_input_tokens": 2048, "skill_sha256": hashes,
            "cases_sha256": hashlib.sha256(args.cases.read_bytes()).hexdigest(),
            "rounds": args.rounds, "seed": 20261010, "case_count": len(cases),
            "development_cases": sum(case["split"] == "development" for case in cases),
            "heldout_cases": sum(case["split"] == "heldout" for case in cases),
            "decision_session_load_ms": round(load_ms, 3), "prewarm_ms": prewarm,
            "timing_scope": "SDK only; excludes loading, prewarming, Go IPC and main LLM. Boolean latency includes both skill evaluations.",
            "comparison": "Actual bundled English descriptions vs Korean choice descriptions vs independent English boolean questions. No main-LLM baseline or production integration.",
        }, "results": [], "summary": {},
    }
    generator = random.Random(20261010)
    tasks = [(strategy, case, run) for run in range(args.rounds)
             for strategy in ["english_choice", "korean_choice", "per_skill_boolean"] for case in cases]
    generator.shuffle(tasks)
    try:
        for index, (strategy, case, run) in enumerate(tasks):
            text = case["text"]
            if case.get("context"):
                text = "Previous conversation:\n" + case["context"] + "\nCurrent user request:\n" + text
            row = {"id": case["id"], "split": case["split"], "tags": case.get("tags", []),
                   "strategy": strategy, "run": run, "text": case["text"], "expected": case["expected"]}
            started = time.perf_counter()
            predicted, probabilities = [], {}
            try:
                if strategy in questions:
                    result = engine.evaluate_choice(text, questions[strategy])
                    predicted = LABELS[result.selected_key]
                    probabilities = result.probabilities
                    row["confidence"] = result.confidence
                else:
                    for name, question in booleans.items():
                        result = engine.evaluate_boolean(text, question)
                        probabilities[name] = result.probability_true
                        if result.value:
                            predicted.append(name)
            except Exception as exc:
                row["error"] = str(exc)
            row["elapsed_ms"] = round((time.perf_counter() - started) * 1000, 3)
            row["predicted"] = sorted(predicted)
            row["probabilities"] = probabilities
            # Mirror the existing loader's explicit-request recognition. A
            # deterministic override must never suppress a named skill.
            explicit = {name for name in SKILL_NAMES if any(
                word.rstrip(",.;:!?()[]").lower() in ("$" + name, "$builtin:" + name)
                for word in case["text"].split())}
            row["guarded_predicted"] = sorted(set(predicted) | explicit)
            report["results"].append(row)
            if (index + 1) % 60 == 0:
                print(f"evaluated {index + 1}/{len(tasks)} decisions", flush=True)
    finally:
        engine.close()

    summarize(report)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(report, ensure_ascii=False, indent=2, allow_nan=False) + "\n")
    print(json.dumps({"metadata": report["metadata"], "heldout": {
        strategy: values["heldout"] for strategy, values in report["summary"].items()}}, ensure_ascii=False, indent=2), flush=True)


if __name__ == "__main__":
    main()
