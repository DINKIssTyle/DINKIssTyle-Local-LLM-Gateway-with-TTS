import assert from 'node:assert/strict';
import {TranslationSentence} from './translation-sentence.mjs';
import {SpeechSegmenter,speechSegmentOptions} from './audio-segments.mjs';
const at=ms=>new Date(1700000000000+ms).toISOString();
const job=(id,prompt,start,end,draft=false)=>({id,prompt,source:'en',target:'ko',startedAt:at(start),endedAt:at(end),draft});
const sentence=new TranslationSentence();
assert.equal(sentence.update(job('a','Could',0,600,true)).prompt,'Could');
assert.equal(sentence.update(job('a','Could you',0,1200,true)).prompt,'Could you','live text replaces its earlier hypothesis');
assert.equal(sentence.update(job('a','Could you',0,2000)).prompt,'Could you');
const continued=sentence.update(job('b','help',2200,2600,true));assert.equal(continued.historyId,'a');
assert.equal(continued.prompt,'Could you help','a short audio endpoint must not discard the start of a sentence');
assert.equal(sentence.update(job('b','help me',2200,3100,true)).prompt,'Could you help me');
assert.equal(sentence.update(job('b','help me today?',2200,4000)).prompt,'Could you help me today?');
assert.equal(sentence.update(job('b','late wrong draft',2200,4100,true)),null);
assert.equal(sentence.update(job('c','Yes',4300,4800,true)).prompt,'Yes','explicit sentence punctuation starts a new sentence');
assert.equal(sentence.update(job('d','New topic',8000,8500,true)).prompt,'New topic','long silence clears old sentence context');
assert.equal(sentence.update(job('c','delayed final',4300,5000)),null,'old results cannot rewind the display');
sentence.reset();
sentence.update(job('a','first draft',0,500,true));
sentence.update(job('b','second draft',1000,1500,true));
assert.equal(sentence.update(job('a','First',0,900)),null,'late final updates context without submitting newer unfinished speech to LLM');
assert.equal(sentence.update(job('b','second',1000,2100)).prompt,'First second');
assert.equal(sentence.update({...job('c','fresh language',2400,2900,true),source:'ja'}).prompt,'fresh language');
const bounded=new TranslationSentence({maxSpanMs:3000,maxChars:12});
bounded.update(job('a','123456',0,1000));
assert.equal(bounded.update(job('b','7890123',1200,2000)).prompt,'7890123');
assert.equal(bounded.update(job('c','span',2200,6000)).prompt,'span');
assert.deepEqual(speechSegmentOptions('whisper','translate'),{});
const vad=new SpeechSegmenter(speechSegmentOptions('chrome-online','translate'));
const speech=new Uint8Array(3200);const view=new DataView(speech.buffer);for(let i=0;i<speech.length;i+=2)view.setInt16(i,5000,true);
for(let i=0;i<6;i++)vad.push(speech);
for(let i=0;i<10;i++)assert.equal(vad.push(new Uint8Array(3200)),null,'a brief pause between words must not close Chrome translation audio');
for(let i=0;i<6;i++)vad.push(speech);
let final=null;for(let i=0;i<16;i++)final=vad.push(new Uint8Array(3200)) || final;
assert.ok(final && final.length===3200*38,'the endpoint contains both sides of the brief pause');
assert.equal(vad.flush(),null);
console.log('PASS: translation sentence accumulation, corrections, late finals, boundaries and Chrome endpoint');
