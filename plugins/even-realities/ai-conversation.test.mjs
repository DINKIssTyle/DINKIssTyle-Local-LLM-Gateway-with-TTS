import assert from 'node:assert/strict';
import {ChatMemory,routeAIUtterance} from './ai-conversation.mjs';
import {normalizeGlassesMode,nextGlassesMode,glassesModeMenuIdToMode} from './hud-status.mjs';
assert.equal(normalizeGlassesMode('transcript'),'ai','migrate previously saved transcription mode');
assert.equal(nextGlassesMode('ai'),'translate');assert.equal(nextGlassesMode('translate'),'ai');
assert.equal(glassesModeMenuIdToMode(1),'ai');assert.equal(glassesModeMenuIdToMode(2),'translate');assert.equal(glassesModeMenuIdToMode(3),null);
const ack=routeAIUtterance({text:'웬즈 데이',triggered:true,prompt:''},{name:'웬즈데이'});
assert.deepEqual(ack,{kind:'ack',waiting:true,ack:'웬즈데이: 듣는 중...'});
assert.equal(routeAIUtterance({text:'',rejected:true},{waiting:true}).waiting,true,'empty/rejected input must not consume the armed question');
assert.equal(routeAIUtterance({text:'피라미드의 건립 목적은 뭐야'},{waiting:ack.waiting}).prompt,'피라미드의 건립 목적은 뭐야');
assert.equal(routeAIUtterance({text:'웬즈데이야',triggered:true,prompt:'야'},{name:'웬즈데이'}).kind,'ack');
const chat=routeAIUtterance({text:'웬즈 데이 그건 언제야',triggered:true,prompt:'그건 언제야'});
assert.equal(chat.prompt,'그건 언제야');assert.equal(chat.waiting,false);
assert.equal(routeAIUtterance({text:'그 뒤에는 청동기 시대 얘기야'}).kind,'ambient','untriggered next speech returns to ambient mode');
assert.equal(routeAIUtterance({text:'웬즈데이',triggered:true,prompt:''},{waiting:true,name:'웬즈데이'}).kind,'ack');
const memory=new ChatMemory();
assert.equal(memory.context('gateway/user/model'),'');
for(let i=0;i<12;i++)memory.remember('gateway/user/model','질문 '+i,'답변 '+i);
assert.equal(memory.turns.length,8);assert.match(memory.context('gateway/user/model'),/^질문: 질문 4/);
assert.equal(memory.context('gateway/other-user/model'),'','account changes must clear previous chat context');
memory.remember('gateway/user/model','늦은 이전 계정 질문','늦은 답변');assert.equal(memory.turns.length,0);
memory.remember('gateway/other-user/model','현재 질문','현재 답변');
assert.equal(memory.context('gateway/other-user/new-model'),'','model changes must start a separate context');
for(let i=0;i<20;i++)memory.remember('gateway/other-user/new-model','질문 '.repeat(300),'답변 '.repeat(1000));
assert.ok(memory.context('gateway/other-user/new-model').length<=8000);
assert.ok(memory.turns.length<=8);
console.log('PASS: two modes, legacy migration, wake-only acknowledgement, next-utterance routing, bounded isolated chat history and scope changes');
