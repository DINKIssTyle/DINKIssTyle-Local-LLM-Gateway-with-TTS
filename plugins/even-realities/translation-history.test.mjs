import assert from 'node:assert/strict';
import {TranslationHistory} from './translation-history.mjs';
const history=new TranslationHistory();
for(let i=0;i<40;i++)history.update('s'+i,'번역 문장 '+i,{final:true});
assert.equal(history.window().totalLines,30);assert.equal(history.entries.length,30);
assert.doesNotMatch(history.text(),/번역 문장 9\n/);assert.match(history.text(),/^번역 문장 10/);
assert.equal(history.window().visibleText.split('\n').length,5);
assert.match(history.window().visibleText,/번역 문장 39$/);
history.scroll(-10);const pinned=history.window().visibleText;
history.update('s40','번역 문장 40',{final:true});
assert.equal(history.window().visibleText,pinned,'evicting old rows must preserve a manually selected viewport');
assert.equal(history.follow,false);
for(let i=0;i<40;i++)history.scroll(1);
assert.equal(history.follow,true);assert.match(history.window().visibleText,/번역 문장 40$/);
history.reset();
history.update('first','첫 번역',{final:true});
history.update('second','임시 번역');history.update('second','교정한 번역');
assert.equal(history.entries.length,2);assert.equal(history.text(),'첫 번역\n교정한 번역');
history.update('second','확정 번역',{final:true});history.update('second','늦은 임시 결과');
assert.equal(history.text(),'첫 번역\n확정 번역');
assert.equal(history.update('first','늦은 이전 문장',{final:true}),false);
assert.equal(history.update('empty',''),false);assert.equal(history.update('empty','…'),false);
// A continued sentence shares one display entry across separate audio endpoints.
history.update('second','확정 번역에 이어 말하는 중',{revision:'next-audio'});
assert.equal(history.entries.length,2);assert.match(history.text(),/이어서|이어 말하는 중/);
history.update('second','이어진 문장 전체 확정',{revision:'next-audio',final:true});
assert.equal(history.entries.length,2);
history.reset();history.update('long','긴 번역 문장입니다. '.repeat(3000),{final:true});
assert.ok(history.window().totalLines<=30);assert.ok(history.text().length<=6030);assert.ok(history.entries.length<=30);
const limit=new TranslationHistory({maxChars:100,maxLines:30});
for(let i=0;i<100;i++)limit.update(i,'1234567890',{final:true});
assert.ok(limit.entries.reduce((n,e)=>n+e.lines.join('').length,0)<=100);
history.reset();assert.equal(history.window().fullText,'');assert.equal(history.follow,true);
let now=1000;
const timed=new TranslationHistory({now:()=>now});
timed.update('first','이전 문장');
now=2000;timed.update('first','이전 문장',{final:true});
timed.update('second','최근 문장',{final:true});
now=4000;timed.expireBefore(now-3000);
assert.equal(timed.text(),'최근 문장','an identical final update does not extend the display time');
assert.equal(timed.update('first','늦은 발음',{refresh:false}),false);
now=5000;timed.expireBefore(now-3000);
assert.equal(timed.text(),'');
console.log('PASS: 30-row/character-bounded translation history, stable viewport, live correction, final replacement, sentence continuation and stale results');
