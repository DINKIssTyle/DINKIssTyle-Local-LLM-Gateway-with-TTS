import assert from 'node:assert/strict';
import {ROLE_MODEL_KEYS,normalizeRoleModels,resolveRoleModel,llmRequestRole,roleModelOptions,translationOnlyPrompts} from './role-models.mjs';
assert.deepEqual(normalizeRoleModels(null),{chat:'',hint:'',translation:'',translationReply:''});
const config={model:'base',roleModels:{chat:'chat',hint:'hint',translation:'translate',translationReply:'reply'}};
for(const role of ROLE_MODEL_KEYS)assert.equal(resolveRoleModel(role,config),config.roleModels[role]);
assert.equal(resolveRoleModel('chat',{model:'new-base',roleModels:{chat:''}}),'new-base');
assert.equal(resolveRoleModel('chat',{model:'new-base',roleModels:{chat:'fixed'}}),'fixed');
assert.equal(resolveRoleModel('hint',{model:'base',roleModels:{hint:{invalid:true}}}),'base');
assert.equal(llmRequestRole({mode:'ai',chatSession:true}),'chat');
assert.equal(llmRequestRole({mode:'ai',chatSession:false}),'hint');
assert.equal(llmRequestRole({mode:'translate'}),'translation');
assert.equal(llmRequestRole({mode:'translate',translated:true}),'translationReply');
const models=[{id:'other',label:'Other'},{id:'base',label:'Base'}];
const options=roleModelOptions(models,'base','missing');
assert.equal(options[0].id,'');assert.match(options[0].label,/기본 모델 사용.*Base/);assert.equal(options[1].id,'base');
assert.equal(options.at(-1).id,'missing');assert.match(options.at(-1).label,/현재 목록에 없음/);
assert.match(translationOnlyPrompts('Coffee?','en','ko').systemPrompt,/"translation"/);
assert.match(translationOnlyPrompts('Coffee?','en','ko').systemPrompt,/답변 예시를 만들지 마세요/);
console.log('PASS: per-role model resolution, default inheritance, explicit pinning, request-role mapping and translation-only prompts');
