import assert from 'node:assert/strict';
import {EnginePreparation,waitForPreparation} from './engine-preparation.mjs';
const tick=()=>new Promise(resolve=>setImmediate(resolve));
let release;const calls=[],states=[];
const queue=new EnginePreparation(async spec=>{
  calls.push(spec.key);
  if(spec.key==='slow')await new Promise(resolve=>release=resolve);
  if(spec.key==='bad')throw Error('not installed');
},(state,spec)=>states.push([state,spec.key]));
const slow=queue.ensure({key:'slow'});
assert.equal(queue.ensure({key:'slow'}),slow,'reuse in-flight preparation');
const dropped=queue.ensure({key:'dropped'});const latest=queue.ensure({key:'latest'});
await assert.rejects(dropped,{name:'AbortError'});
release();await slow;await latest;
assert.deepEqual(calls,['slow','latest'],'rapid changes prepare only the latest waiting configuration');
assert.ok(!states.some(([state,key])=>state==='ready' && key==='slow'),'stale completion cannot overwrite current status');
await queue.ensure({key:'latest'});assert.equal(calls.length,2,'ready current configuration is reused');
await queue.ensure({key:'latest'},{force:true});assert.equal(calls.length,3,'manual retry and capture start can revalidate');
await assert.rejects(queue.ensure({key:'bad'}));await assert.rejects(queue.ensure({key:'bad'}));
assert.equal(calls.filter(key=>key==='bad').length,2,'failed preparation can be retried');
const active=queue.ensure({key:'slow'});const pending=queue.ensure({key:'removed'});queue.clear();
await assert.rejects(pending,{name:'AbortError'});release();await active;
assert.ok(!states.slice(-2).some(([state,key])=>state==='ready' && key==='slow'),'switching to LLM suppresses old native readiness');
let finish;
const shared=new EnginePreparation(()=>new Promise(resolve=>finish=resolve));
const controller=new AbortController();const preparing=shared.ensure({engine:'apple',language:'ko'});
const capture=waitForPreparation(preparing,controller.signal);controller.abort();
await assert.rejects(capture,{name:'AbortError'});finish();await preparing;
assert.equal(shared.ready,JSON.stringify({engine:'apple',language:'ko'}),'capture cancellation must not cancel shared language preparation');
await tick();
console.log('PASS: automatic preparation deduplicates, keeps latest settings, rejects stale UI, retries failures and preserves shared downloads on capture stop');
