import assert from 'node:assert/strict';
import {compareHintDuplicate,PreviewIntent,ChatSettingsCache,VoiceLatency} from './realtime-hints.mjs';
const preview=new PreviewIntent();
const input={id:'one',text:'웬즈 데이 청동기 시대는 언제야',aliases:['웬즈데이','웸즈 데이']};
assert.equal(preview.observe(input).wake,false,'one unconfirmed draft cannot prepare chat');
assert.equal(preview.observe(input).newWake,true,'two agreeing drafts recognize spaced aliases');
assert.equal(preview.observe(input).newWake,false,'one preparation per continuous wake observation');
assert.equal(preview.observe({...input,text:'청동기 시대는 언제부터일까'}).wake,false,'corrected drafts release speculative wake');
assert.equal(preview.observe({...input,id:'two',text:'청동기 시대는 청동으로 도구를 만들었다',stableText:'청동기 시대는 청동으로'}).hintText,'청동기 시대는 청동으로');
