assert.equal(preview.observe({id:'punctuation',text:'E.D.I.T.H please',stableText:'E.D.I.T.H please',aliases:['edith']}).wake,false,'punctuation is not silently removed from an alias');

let now=0,calls=0,release;
const cache=new ChatSettingsCache({now:()=>now,ttlMs:100});
const load=()=>{calls++;return new Promise(resolve=>{release=()=>resolve({llm_mode:'standard'});});};
const prepared=cache.read('server/token',load);
const controller=new AbortController(),cancelled=cache.read('server/token',load,controller.signal);
await Promise.resolve();controller.abort();await assert.rejects(cancelled,{name:'AbortError'});
release();assert.equal((await prepared).llm_mode,'standard');
await cache.read('server/token',load);assert.equal(calls,1,'speculation is shared and one cancelled consumer cannot cancel others');
now=101;await cache.read('server/token',async()=>{calls++;return {llm_mode:'stateful'};});assert.equal(calls,2);
