assert.equal(preview.observe({...input,id:'three',text:'짧음',stableText:'짧음'}).hintText,'');
assert.equal(preview.observe({id:'latin',text:'holiday tomorrow',stableText:'holiday tomorrow',aliases:['day']}).wake,false,'Latin aliases must be whole words, as in final transcription');
