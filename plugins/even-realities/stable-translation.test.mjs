import assert from 'node:assert/strict';
import {StableTranslation,translationChunks} from './stable-translation.mjs';
const signal=new AbortController().signal;
const calls=[];
const engine=new StableTranslation(async job=>{calls.push(job.prompt);return {ok:true,text:`번역(${job.prompt})`};});
const job=(prompt,stableText='',extra={})=>({id:'one',engine:'apple',source:'en',target:'ko',draft:true,prompt,stableText,...extra});
const first=await engine.run(job('We agreed. I think','We agreed.'),signal);
assert.deepEqual(calls,['We agreed.','I think']);
const second=await engine.run(job('We agreed. I think we should wait','We agreed.'),signal);
assert.deepEqual(calls,['We agreed.','I think','I think we should wait']);
assert.ok(second.text.startsWith('번역(We agreed.)'),'committed translation stays identical while tail grows');
await engine.run(job('We agreed. I think we should wait.','',{draft:false}),signal);
assert.equal(calls.filter(t=>t==='We agreed.').length,1,'final reuses exact confirmed sentence');
await engine.run(job('We disagreed. I think we should wait.','',{draft:false}),signal);
assert.equal(calls.at(-1),'We disagreed.','authoritative correction can repair earlier recognition');
assert.deepEqual(translationChunks('한국어입니다. 다음은','한국어입니다.'),['한국어입니다.','다음은']);
assert.deepEqual(translationChunks('I thought the manager would','I thought the manager'),['I thought the manager would'],'no punctuation means keep unfinished sentence context');
assert.deepEqual(translationChunks('A corrected source. More','Wrong source.'),['A corrected source. More'],'mismatched stable prefix must never discard input');
assert.deepEqual(translationChunks('Dr. Smith arrived. More','Dr. Smith arrived.'),['Dr. Smith arrived.','More']);
assert.deepEqual(translationChunks('一文です。次の文','一文です。'),['一文です。','次の文']);
const before=calls.length;
await engine.run(job('We agreed.','',{id:'two',draft:false}),signal);
assert.equal(calls.length,before+1,'new audio segment gets a separate cache');
await engine.run(job('We agreed.','',{id:'two',target:'ja',draft:false}),signal);
assert.equal(calls.length,before+2,'language direction gets a separate cache');
let count=0;
const retry=new StableTranslation(async()=>++count===1?{ok:false,reason:'busy'}:{ok:true,text:'성공'});
assert.equal((await retry.run(job('test'),signal)).ok,false);
assert.equal((await retry.run(job('test'),signal)).text,'성공','failures are never cached');
const controller=new AbortController();let release;
const cancelled=new StableTranslation(async()=>await new Promise(resolve=>release=resolve));
const pending=cancelled.run(job('pending'),controller.signal);controller.abort();release({ok:true,text:'late'});
await assert.rejects(pending);assert.equal(cancelled.cache.size,0,'cancelled result cannot poison sentence cache');
const bounded=new StableTranslation(async()=>({ok:true,text:'x'.repeat(50)}),{maxEntries:2,maxChars:150});
for(let i=0;i<20;i++)await bounded.run(job('source '+i),signal);
assert.ok(bounded.cache.size<=2);assert.ok([...bounded.cache].reduce((n,[k,v])=>n+k.length+v.length,0)<=150);
let committedCalls=0;
const longTail=new StableTranslation(async j=>{if(j.prompt==='Keep this.')committedCalls++;return{ok:true,text:j.prompt};},{maxEntries:4});
for(let i=0;i<50;i++)await longTail.run(job('Keep this. Tail '+i,'Keep this.'),signal);
assert.equal(committedCalls,1,'frequent tail revisions must not evict the committed sentence');
console.log('PASS: stable sentence translations survive growing tails, final correction, language/reset isolation, cancellation, bounded cache and failed retry');
